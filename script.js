function refreshBlock(type) {
  const block = textElements[type];
  if (!block.el) return;

  block.el.style.opacity = 0;

  setTimeout(() => {
    let next;
    do {
      next = Math.floor(Math.random() * block.data.length);
    } while (next === block.last && block.data.length > 1);

    block.last = next;
    block.el.innerText = block.data[next];
    block.el.style.opacity = 1;
  }, 500);
}

// Кнопки
document.getElementById("random-btn").onclick = () => refreshBlock('msfo');
document.getElementById("nsbu-btn").onclick = () => refreshBlock('nsbu');

// Клавиатура
document.addEventListener("keydown", (e) => {
  if (e.code === "Space") { refreshBlock('msfo'); refreshBlock('nsbu'); }
  if (e.key === "ArrowUp") refreshBlock('msfo');
  if (e.key === "ArrowDown") refreshBlock('nsbu');
});

// Авто-старт
['msfo', 'nsbu'].forEach((type, i) => {
  refreshBlock(type);
  setInterval(() => refreshBlock(type), 30000 + (i * 5000));
});